def build_chunks() -> list[dict]:
    """生成 L1-L4 全部分块（对齐 TextChunk 字段）"""
    from content.theses_raw import THESES_RAW, get_raw_text

    chunks: list[dict] = []
    for n, th in enumerate(THESES_RAW, start=1):
        pid = th["paragraph_id"]
        ann = THESIS_ANNOTATIONS[n]
        raw = get_raw_text(pid)

        chunks.append({
            "id": _cid(n, 1), "layer": 1, "source": WORK_TITLE,
            "source_location": f"第{n}条", "paragraph_id": pid,
            "text": raw, "orthodoxy_tag": "经典原著", "authority_score": 1.0,
            "logical_type": "primary_text", "concept_mentions": [ann["concept"]],
        })
        chunks.append({
            "id": _cid(n, 2), "layer": 2, "source": WORK_TITLE,
            "source_location": f"第{n}条·命题", "paragraph_id": pid,
            "text": ann["proposition"], "orthodoxy_tag": "正统", "authority_score": 0.95,
            "logical_type": "proposition", "concept_mentions": [ann["concept"]],
        })
        chunks.append({
            "id": _cid(n, 3), "layer": 3, "source": "正典注释（艾思奇·统编教材）",
            "source_location": f"第{n}条·注释", "paragraph_id": pid,
            "text": ann["annotation"], "orthodoxy_tag": "正统", "authority_score": 0.9,
            "logical_type": "annotation", "concept_mentions": [ann["concept"]],
        })
        chunks.append({
            "id": _cid(n, 4), "layer": 4, "source": "正典解析（统编教材）",
            "source_location": f"第{n}条·解析", "paragraph_id": pid,
            "text": ann["analysis"], "orthodoxy_tag": "正统", "authority_score": 0.9,
            "logical_type": "analysis", "concept_mentions": [ann["concept"]],
        })
    return chunks


def chunks_for_paragraph(paragraph_id: str) -> list[dict]:
    """取某条提纲的全部 L1-L4 分块"""
    return [c for c in build_chunks() if c["paragraph_id"] == paragraph_id]
