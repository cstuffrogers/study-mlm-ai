def build_route_nodes() -> tuple[list[dict], list[tuple[str, str]]]:
    """把 ROUTE_NODES 展开为完整节点列表 + 依赖边（章内顺序链 + 跨章衔接），构成 DAG。

    返回：(nodes, edges)。edges 为 (node_id, prereq_id) 形式。
    与 content/knowledge_graph.py 中 sec_A_02 的既有节点/边合并时不冲突（id 不重叠）。
    """
    nodes: list[dict] = []
    edges: list[tuple[str, str]] = []
    # 每条路线：上一个章节的末节点，用于跨章衔接
    last_of_route: dict[str, str] = {}

    for section_id, defs in ROUTE_NODES.items():
        route_id = "route_" + section_id.split("_")[1]
        prev_in_section = None
        first_in_section = None
        for d in defs:
            node = {
                "id": d["id"], "name": d["name"], "section_id": section_id,
                "ability_dim": d["ability_dim"], "exam_weight": d["exam_weight"],
                "definition": d.get("definition", ""),
                "source_chunk_id": d.get("source_chunk_id", ""),
                "paragraph": "",
            }
            nodes.append(node)
            if first_in_section is None:
                first_in_section = d["id"]
            if prev_in_section:
                edges.append((d["id"], prev_in_section))  # 章内顺序链
            prev_in_section = d["id"]
        # 跨章衔接：本章首节点依赖上一章末节点（同路线）
        if first_in_section and route_id in last_of_route:
            edges.append((first_in_section, last_of_route[route_id]))
        if prev_in_section:
            last_of_route[route_id] = prev_in_section
    return nodes, edges


def guide_for(section_id: str) -> dict | None:
    return CHAPTER_GUIDES.get(section_id)


@lru_cache(maxsize=1)
def _route_node_index() -> dict[str, dict]:
    """`ROUTE_NODES` 原始定义 → `build_route_nodes()` 展开后的完整节点。

    两条路径原先不一致：`build_route_nodes()` 会给每个节点补 `section_id` /
    `definition` / `paragraph`，而 `nodes_for_section()` 直接回原始 defs，导致
    接口与离线包里的节点缺 `section_id`（读者端按 section_id 分组就落进空键）。
    """
    nodes, _edges = build_route_nodes()
    return {n["id"]: n for n in nodes}


def _with_definition(node: dict) -> dict:
    """补齐 `definition`（sec_A_02 的 12 个提纲节点原先不带该字段）。

    定义取自 `theses_concepts.CONCEPTS` 里同名的规范释义（我们自己写的导读释义，
    不是原著正文）；`思维的此岸性` 按概念表里的 `此岸性` 对上。
    """
    if node.get("definition"):
        return node
    try:
        from content.theses_concepts import CONCEPTS
    except Exception:  # pragma: no cover - 内容层异常不应阻断接口
        return {**node, "definition": ""}
    name = node.get("name") or ""
    for c in CONCEPTS:
        if c["name"] == name or name.endswith(c["name"]):
            return {**node, "definition": c.get("canonical_definition", "")}
    return {**node, "definition": ""}


def nodes_for_section(section_id: str) -> list[dict]:
    """当前章节的知识点（含 sec_A_02 的既有 12 节点）。

    统一返回「完整形状」：id / name / section_id / ability_dim / exam_weight /
    definition / source_chunk_id / paragraph，与 `build_route_nodes()` 一致。
    """
    if section_id == "sec_A_02":
        from content.knowledge_graph import nodes_by_section
        return [_with_definition(n) for n in nodes_by_section(section_id)]
    index = _route_node_index()
    out: list[dict] = []
    for d in ROUTE_NODES.get(section_id, []):
        full = index.get(d["id"])
        out.append(dict(full) if full else {**d, "section_id": section_id})
    return out


def all_new_nodes() -> list[dict]:
    nodes, _ = build_route_nodes()
    return nodes
